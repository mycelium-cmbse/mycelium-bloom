import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const directory = fileURLToPath(new URL('.', import.meta.url));
const lock = JSON.parse(await readFile(new URL('package-lock.json', import.meta.url), 'utf8'));
const expected = { '@antv/x6': '3.1.7', 'dom-align': '1.12.4', 'lodash-es': '4.18.1', mousetrap: '1.6.5', 'utility-types': '3.11.0', tslib: '2.8.1', esbuild: '0.28.2' };
const dependencies = [];
for (const [name, version] of Object.entries(expected)) {
    const entry = lock.packages[`node_modules/${name}`];
    const installed = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, import.meta.url), 'utf8'));
    if (entry?.version !== version || installed.version !== version || !entry.resolved.startsWith('https://registry.npmjs.org/')) {
        throw new Error(`Unreviewed dependency: ${name}`);
    }
    dependencies.push({ name, version, integrity: entry.integrity, license: entry.license });
}
if (lock.packages['node_modules/@antv/x6'].integrity !== 'sha512-NLKXtbCK51oLbazfFD0XsD93rMmih08UBW4gAuEyLBpwAqHmHe+vP8VhOZDkl5O9jV1LSv85IJghr9CT5tZjWw==') {
    throw new Error('X6 archive integrity differs from the reviewed release.');
}

const result = await build({
    absWorkingDir: directory,
    stdin: { contents: "export { Graph, routerPresets } from '@antv/x6';", resolveDir: directory, sourcefile: 'entry.js' },
    bundle: true, format: 'esm', platform: 'browser', target: ['es2022'], supported: { 'template-literal': false }, minify: true,
    legalComments: 'none', write: false, charset: 'utf8', sourcemap: false
});
const script = '// Generated by Build/DiagramAssets/generate.mjs; see LICENSES.txt.\n' + result.outputFiles[0].text;
const notices = [];
for (const [name, license] of [['@antv/x6', 'LICENSE'], ['dom-align', 'LICENSE.md'], ['lodash-es', 'LICENSE'], ['mousetrap', 'LICENSE'], ['utility-types', 'LICENSE'], ['tslib', 'LICENSE.txt']]) {
    notices.push(`${name} ${expected[name]}\n${await readFile(new URL(`node_modules/${name}/${license}`, import.meta.url), 'utf8')}`);
}
const artifacts = {
    'x6.js': script,
    'LICENSES.txt': notices.join('\n\n').replaceAll('\r\n', '\n'),
    'manifest.json': JSON.stringify({ generator: 'esbuild 0.28.2', dependencies,
        sha256: createHash('sha256').update(script).digest('hex') }, null, 2) + '\n'
};
const output = new URL('../../wwwroot/vendor/x6/', import.meta.url);
const verify = process.argv.includes('--verify');
if (!verify) await mkdir(output, { recursive: true });
for (const [name, content] of Object.entries(artifacts)) {
    const path = new URL(name, output);
    if (verify) {
        if (await readFile(path, 'utf8') !== content) throw new Error(`Generated diagram asset differs: ${name}`);
    } else {
        await writeFile(path, content);
    }
}
console.log(verify ? 'Diagram assets verified.' : 'Diagram assets generated.');
