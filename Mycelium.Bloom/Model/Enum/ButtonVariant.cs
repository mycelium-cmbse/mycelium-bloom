namespace Mycelium.Bloom.Model
{
    /// <summary>
    /// Defines the available button visual variants.
    /// </summary>
    public enum ButtonVariant
    {
        /// <summary>
        /// Represents the primary button style used for main actions.
        /// </summary>
        Primary,

        /// <summary>
        /// Represents the secondary button style used for supporting actions.
        /// </summary>
        Secondary,

        /// <summary>
        /// Represents a minimal button style with reduced visual emphasis.
        /// </summary>
        Ghost,

        /// <summary>
        /// Represents a danger button style used for destructive or critical actions.
        /// </summary>
        Danger
    }
}
