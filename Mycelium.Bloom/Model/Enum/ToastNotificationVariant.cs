namespace Mycelium.Bloom.Model.Enum
{
    /// <summary>
    /// Defines the visual variants available for toast notifications.
    /// </summary>
    public enum ToastNotificationVariant
    {
        /// <summary>
        /// Represents informational feedback.
        /// </summary>
        Info,

        /// <summary>
        /// Represents successful feedback.
        /// </summary>
        Success,

        /// <summary>
        /// Represents warning feedback.
        /// </summary>
        Warning,

        /// <summary>
        /// Represents dangerous or error feedback.
        /// </summary>
        Danger
    }
}
