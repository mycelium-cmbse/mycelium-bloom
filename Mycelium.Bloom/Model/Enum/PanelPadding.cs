namespace Mycelium.Bloom.Model.Enum
{
    /// <summary>
    /// Defines the available panel padding sizes.
    /// </summary>
    public enum PanelPadding
    {
        /// <summary>
        /// Represents a panel without padding.
        /// </summary>
        None,

        /// <summary>
        /// Represents a small panel padding.
        /// </summary>
        Small,

        /// <summary>
        /// Represents the default medium panel padding.
        /// </summary>
        Medium,

        /// <summary>
        /// Represents a large panel padding.
        /// </summary>
        Large
    }
}
